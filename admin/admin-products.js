const quillTr = new Quill("#editorTr", { theme: "snow" });
const quillEn = new Quill("#editorEn", { theme: "snow" });

let products = [];
let selectedProductId = null;
let images = [];
let datasheetUrl = "";
let slugAutoGenerated = "";

function slugify(text) {
  return (text || "")
    .toLowerCase()
    .replace(/ğ/g, "g").replace(/ü/g, "u").replace(/ş/g, "s")
    .replace(/ı/g, "i").replace(/ö/g, "o").replace(/ç/g, "c")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function escapeHtml(str) {
  const div = document.createElement("div");
  div.textContent = str;
  return div.innerHTML;
}

// ---- Lang tabs ----
document.querySelectorAll(".lang-tab").forEach(tab => {
  tab.addEventListener("click", () => {
    document.querySelectorAll(".lang-tab").forEach(t => t.classList.remove("active"));
    document.querySelectorAll(".lang-pane").forEach(p => p.classList.remove("active"));
    tab.classList.add("active");
    document.querySelector(`[data-lang-pane="${tab.dataset.lang}"]`).classList.add("active");
  });
});

// ---- List ----
async function loadProducts() {
  const { data, error } = await sb.from("products").select("*").order("sort_order", { ascending: true });
  if (error) { console.error(error); return; }
  products = data || [];
  renderList();
}

function renderList() {
  const list = document.getElementById("productList");
  list.innerHTML = "";
  products.forEach(product => {
    const item = document.createElement("div");
    item.className = "admin-list-item" + (product.id === selectedProductId ? " active" : "");
    item.innerHTML = `
      <span class="title">${escapeHtml(product.name_tr || "(Adsız)")}</span>
      <span class="meta"><span class="status-dot ${product.published ? "published" : "draft"}"></span>${product.published ? "Yayında" : "Taslak"}</span>
    `;
    item.addEventListener("click", () => selectProduct(product.id));
    list.appendChild(item);
  });
}

function resetForm() {
  selectedProductId = null;
  images = [];
  datasheetUrl = "";
  slugAutoGenerated = "";
  document.getElementById("nameTr").value = "";
  document.getElementById("nameEn").value = "";
  document.getElementById("shortDescTr").value = "";
  document.getElementById("shortDescEn").value = "";
  document.getElementById("slug").value = "";
  document.getElementById("category").value = "oil";
  document.getElementById("sortOrder").value = 0;
  document.getElementById("published").checked = false;
  quillTr.setContents([]);
  quillEn.setContents([]);
  document.getElementById("deleteBtn").style.display = "none";
  document.getElementById("statusMsg").textContent = "";
  renderImages();
  renderDatasheet();
  renderList();
}

function selectProduct(id) {
  const product = products.find(p => p.id === id);
  if (!product) return;
  selectedProductId = product.id;
  images = [...(product.images || [])];
  datasheetUrl = product.datasheet_url || "";
  document.getElementById("nameTr").value = product.name_tr || "";
  document.getElementById("nameEn").value = product.name_en || "";
  document.getElementById("shortDescTr").value = product.short_desc_tr || "";
  document.getElementById("shortDescEn").value = product.short_desc_en || "";
  document.getElementById("slug").value = product.slug || "";
  document.getElementById("category").value = product.category || "oil";
  document.getElementById("sortOrder").value = product.sort_order || 0;
  document.getElementById("published").checked = !!product.published;
  quillTr.root.innerHTML = product.description_tr || "";
  quillEn.root.innerHTML = product.description_en || "";
  document.getElementById("deleteBtn").style.display = "inline-block";
  renderImages();
  renderDatasheet();
  renderList();
}

function renderImages() {
  const wrap = document.getElementById("imageList");
  wrap.innerHTML = "";
  images.forEach((url, i) => {
    const thumb = document.createElement("img");
    thumb.className = "upload-thumb";
    thumb.src = url;
    thumb.title = "Kaldırmak için tıklayın";
    thumb.addEventListener("click", () => {
      images.splice(i, 1);
      renderImages();
    });
    wrap.appendChild(thumb);
  });
}

function renderDatasheet() {
  const wrap = document.getElementById("datasheetRow");
  wrap.innerHTML = "";
  if (!datasheetUrl) return;
  const chip = document.createElement("div");
  chip.className = "file-chip";
  chip.innerHTML = `<span>Doküman yüklendi</span>`;
  const removeBtn = document.createElement("button");
  removeBtn.type = "button";
  removeBtn.textContent = "✕";
  removeBtn.addEventListener("click", () => { datasheetUrl = ""; renderDatasheet(); });
  chip.appendChild(removeBtn);
  wrap.appendChild(chip);
}

document.getElementById("nameTr").addEventListener("input", (e) => {
  const slugEl = document.getElementById("slug");
  if (!slugEl.value || slugEl.value === slugAutoGenerated) {
    slugAutoGenerated = slugify(e.target.value);
    slugEl.value = slugAutoGenerated;
  }
});

document.getElementById("newProductBtn").addEventListener("click", resetForm);

document.getElementById("imageInput").addEventListener("change", async (e) => {
  const file = e.target.files[0];
  if (!file) return;
  const path = `${Date.now()}-${file.name}`;
  const { error } = await sb.storage.from("product-media").upload(path, file);
  if (error) { showStatus("Görsel yüklenemedi: " + error.message, false); return; }
  const { data } = sb.storage.from("product-media").getPublicUrl(path);
  images.push(data.publicUrl);
  renderImages();
  e.target.value = "";
});

document.getElementById("datasheetInput").addEventListener("change", async (e) => {
  const file = e.target.files[0];
  if (!file) return;
  const path = `${Date.now()}-${file.name}`;
  const { error } = await sb.storage.from("product-media").upload(path, file);
  if (error) { showStatus("Doküman yüklenemedi: " + error.message, false); return; }
  const { data } = sb.storage.from("product-media").getPublicUrl(path);
  datasheetUrl = data.publicUrl;
  renderDatasheet();
  e.target.value = "";
});

function showStatus(msg, ok) {
  const el = document.getElementById("statusMsg");
  el.textContent = msg;
  el.className = "status-msg " + (ok ? "ok" : "err");
}

document.getElementById("saveBtn").addEventListener("click", async () => {
  const payload = {
    name_tr: document.getElementById("nameTr").value,
    name_en: document.getElementById("nameEn").value,
    short_desc_tr: document.getElementById("shortDescTr").value,
    short_desc_en: document.getElementById("shortDescEn").value,
    description_tr: quillTr.root.innerHTML,
    description_en: quillEn.root.innerHTML,
    slug: document.getElementById("slug").value,
    category: document.getElementById("category").value,
    sort_order: parseInt(document.getElementById("sortOrder").value, 10) || 0,
    published: document.getElementById("published").checked,
    images,
    datasheet_url: datasheetUrl || null
  };

  if (!payload.name_tr || !payload.slug) {
    showStatus("Ad (TR) ve slug zorunludur.", false);
    return;
  }

  let result;
  if (selectedProductId) {
    result = await sb.from("products").update(payload).eq("id", selectedProductId).select().single();
  } else {
    result = await sb.from("products").insert(payload).select().single();
  }

  if (result.error) {
    showStatus("Kaydedilemedi: " + result.error.message, false);
    return;
  }

  selectedProductId = result.data.id;
  document.getElementById("deleteBtn").style.display = "inline-block";
  showStatus("Kaydedildi.", true);
  await loadProducts();
});

document.getElementById("deleteBtn").addEventListener("click", async () => {
  if (!selectedProductId) return;
  if (!confirm("Bu ürünü silmek istediğinize emin misiniz?")) return;
  const { error } = await sb.from("products").delete().eq("id", selectedProductId);
  if (error) { showStatus("Silinemedi: " + error.message, false); return; }
  resetForm();
  await loadProducts();
});

document.addEventListener("DOMContentLoaded", loadProducts);
